import { cp, mkdir, rm, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { selectPublicNotes, selectPublicTutorials } from './note-policy.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(root, 'dist');
const notes = JSON.parse(await readFile(resolve(root, 'content', 'notes.json'), 'utf8'));
const tutorials = JSON.parse(await readFile(resolve(root, 'content', 'tutorials.json'), 'utf8'));
const publicNotes = [...selectPublicNotes(notes), ...selectPublicTutorials(tutorials)];
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
await cp(resolve(root, 'site'), dist, { recursive: true });
const notesJson = `${JSON.stringify(publicNotes, null, 2)}\n`;
const digest = text => createHash('sha256').update(text).digest('hex').slice(0, 16);
const notesFile = `notes.${digest(notesJson)}.json`;
await writeFile(resolve(dist, 'notes.json'), notesJson);
await writeFile(resolve(dist, notesFile), notesJson);
const viewSource = await readFile(resolve(dist, 'note-view.js'), 'utf8');
const viewFile = `note-view.${digest(viewSource)}.js`;
await writeFile(resolve(dist, viewFile), viewSource);
const styleSource = await readFile(resolve(dist, 'style.css'), 'utf8');
const styleFile = `style.${digest(styleSource)}.css`;
await writeFile(resolve(dist, styleFile), styleSource);
const appSource = await readFile(resolve(dist, 'app.js'), 'utf8');
const versionedData = appSource.replace("fetch('./notes.json',", `fetch('./${notesFile}',`);
if (versionedData === appSource) throw new Error('未找到笔记数据入口，无法生成缓存安全的构建。');
const versionedApp = versionedData.replace("from './note-view.js'", `from './${viewFile}'`);
if (versionedApp === versionedData) throw new Error('未找到阅读模块入口，无法生成缓存安全的构建。');
const appFile = `app.${digest(versionedApp)}.js`;
await writeFile(resolve(dist, appFile), versionedApp);
const htmlPath = resolve(dist, 'index.html');
const html = await readFile(htmlPath, 'utf8');
const versionedHtml = html.replace('src="./app.js"', `src="./${appFile}"`).replace('href="./style.css"', `href="./${styleFile}"`);
if (versionedHtml === html) throw new Error('未找到页面脚本入口，无法生成缓存安全的构建。');
await writeFile(htmlPath, versionedHtml);
console.log(`Built ${selectPublicNotes(notes).length} glossary notes and ${selectPublicTutorials(tutorials).length} approved tutorials to ${dist}`);
